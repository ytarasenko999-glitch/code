## How the program of the year affects your life

The program of the year works like the weather: it doesn’t decide for you, but it sets the conditions. Here is how it usually shows up.

### Events and themes that “come by themselves”

If the program of the year holds energies of movement and change, moves, new projects and acquaintances appear almost effortlessly. If it holds energies of stability, life asks for order, discipline and finishing what you started. Fighting the theme of the year is pointless; it is more effective to use it.

### State and mood

The program of the year is noticeable from the inside too. A year with energies of solitude and searching for meaning is often lived more quietly: you want fewer people and more depth. A year with energies of joy and self-expression, on the contrary, pulls you towards visibility, creativity and publicity.

### Money and relationships

Every energy has its own “money” and “relationship” expression. For example, a year with the energy of responsibility and structure is good for career growth but can bring tension into relationships if the person “lives for work”. Knowing this in advance makes it easier to keep the balance.

## Plus and minus: why the same year can be different

Every energy in the matrix has two poles. **In the plus** it gives a resource: courage, intuition, money, love. **In the minus** it shows up through fears, crises, losses and recurring scenarios.

The program of the year is neither “good” nor “bad”. A hard year is usually a year in which the energy is lived in the minus: the person resists the changes the time demands, or repeats an old scenario. When you know what this energy looks like in the plus, you can consciously choose that pole.

> The program of the year is not a verdict but a hint: what to lean on and what to learn this year.

