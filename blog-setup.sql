## Ознаки, що програма кармічного хвоста активна

Хвіст проявляється не постійно, а в певних ситуаціях. Ось типові ознаки:

- **Однакові сценарії з різними людьми.** Різні партнери, колеги чи друзі — а відчуття та фінал ті самі.
- **Сильна емоційна реакція «на рівному місці».** Дрібниця зачіпає непропорційно глибоко — найчастіше це відгук старої програми.
- **Відчуття «я це вже проходила».** Ситуація впізнається ще до того, як розгорнулася.
- **Страх, що не має пояснення в цьому житті.** Наприклад, страх бути на виду, страх грошей або страх довіритися.
- **Повторення в певні роки.** Коли енергія року збігається з енергією хвоста, програма загострюється. Детальніше — у статті про [програму року в матриці долі](/blog/prohrama-roku-matrytsia-doli).

