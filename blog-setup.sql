## Що таке матриця долі

Матриця долі — система самопізнання, яку розробила Наталія Ладіні. Вона будується за датою народження і використовує **22 енергії**, що відповідають 22 Старшим Арканам Таро. Кожна енергія має два полюси — **плюс** (ресурс) і **мінус** (тінь), — а її значення залежить від того, в якій **позиції** матриці вона стоїть.

Тому одна й та сама енергія в позиції «гроші» і в позиції «стосунки» читається по-різному. Головне правило розшифровки: **енергія + позиція = значення**.

