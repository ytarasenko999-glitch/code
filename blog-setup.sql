### 1. Назвіть сценарій словами

Перечитайте опис своїх трьох енергій у мінусі й знайдіть ситуації зі свого життя, які під нього підходять. Запишіть 2–3 конкретні приклади. Сценарій, названий словами, втрачає половину сили.

### 2. Знайдіть точку вибору

У кожному повторюваному сценарії є момент, де ви дієте «на автоматі»: погоджуєтеся, мовчите, тікаєте, рятуєте. Саме тут програма відтворюється. Помітити цей момент — уже половина роботи.

### 3. Розвивайте якість верхньої точки

Верхня енергія хвоста — це ліки. Якщо там енергія відповідальності, урок — брати її на себе, а не перекладати. Якщо енергія любові — вчитися обирати серцем, а не страхом. Подивіться, як ваша верхня енергія виглядає в плюсі, і додайте в життя одну конкретну дію в цьому напрямку.

### 4. Поставте собі правильні питання

У розборі хвоста на сайті є розділ «Питання для себе». Відповідайте письмово — це один із найдієвіших способів побачити програму збоку.

### 5. Перевіряйте рішення

Коли стоїть важливий вибір і ви підозрюєте, що це «знову хвіст», поставте питання в [Таро-трактувальнику](/?go=tarot). Він враховує вашу матрицю долі і допомагає побачити, де діє стара програма, а де — ваше справжнє бажання.

