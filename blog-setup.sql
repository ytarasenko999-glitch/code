## Що таке програма року в матриці долі

Матриця долі будується за датою народження і складається з 22 енергій — тих самих, що й 22 Старші Аркани Таро. Довкола основного квадрата матриці йде **коло віку**: від 0 до 80 років. Кожна точка на цьому колі відповідає певному віку, і в ній стоїть своя енергія.

Програма року — це не одна енергія, а **три енергії, що звучать разом**:

1. **Енергія року** — головна тема, з якою ви проживаєте цей вік.
2. **Протилежна точка** — енергія з протилежного боку кола. Вона показує фон і виклик: як тема року відгукується в іншій сфері життя.
3. **Підсумок року** — сума перших двох. До чого рік приведе, якщо пройти його усвідомлено.

Саме тому два роки з однаковою «головною» енергією можуть проживатися зовсім по-різному: різняться фон і підсумок.

