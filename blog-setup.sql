Кармічний хвіст — це три енергії в нижній частині матриці, на лінії, що йде від центру вниз. У методі Наталії Ладіні їх читають як **завдання, з яким душа прийшла в це втілення**: незавершені уроки, звички та сценарії, які людина «принесла з собою».

Три енергії хвоста мають різні ролі:

- **Нижня точка** — минулий досвід, корінь програми: те, що вже було і що душа знає добре — іноді занадто добре.
- **Середня точка** — як програма проявляється зараз: ситуації та стани, у яких хвіст нагадує про себе.
- **Верхня точка (ближче до центру)** — завдання на це життя: якість, яку важливо розвинути, щоб програма перестала повторюватися.

