/* Builds api/_kb_data.js from tools/kb/*.md — the server-side knowledge base the AI readings are grounded in.
   Run: node tools/kb-build.js */
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, 'kb');
const parse = file => {
  const t = fs.readFileSync(path.join(dir, file), 'utf8');
  const head = (t.match(/^# (.+)$/m) || [, ''])[1].trim();
  const items = {};
  t.split(/^## /m).slice(1).forEach(b => {
    const nl = b.indexOf('\n'), h = b.slice(0, nl).trim(), body = b.slice(nl + 1).trim();
    const id = h.split(/\s+/)[0];
    items[id] = { h, t: body };
  });
  return { head, items };
};
const SPH = ['pers', 'centre', 'tal', 'money', 'love', 'karma', 'rod', 'health', 'pur', 'year'];
const out = { method: fs.readFileSync(path.join(dir, 'method.md'), 'utf8').trim(), mx: {}, tarot: {}, tarotHead: [] };
SPH.forEach(s => { const p = parse(s + '.md'); out.mx[s] = p; if (Object.keys(p.items).length !== 22) throw new Error(s + ': ' + Object.keys(p.items).length); });
['tarot_major.md', 'tarot_minor1.md', 'tarot_minor2.md'].forEach(f => { const p = parse(f); out.tarotHead.push(p.head); Object.assign(out.tarot, p.items); });
if (Object.keys(out.tarot).length !== 78) throw new Error('tarot: ' + Object.keys(out.tarot).length);
fs.writeFileSync(path.join(__dirname, '..', 'api', '_kb_data.js'), '/* generated by tools/kb-build.js from tools/kb/*.md — edit those, not this */\nmodule.exports=' + JSON.stringify(out) + ';\n');
const words = JSON.stringify(out).split(/\s+/).length;
console.log('ok', Object.keys(out.mx).length, 'spheres,', Object.keys(out.tarot).length, 'cards, ~' + words + ' words');
